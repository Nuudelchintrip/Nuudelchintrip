export function getSoumOptions(aimag: string) {
  const location = mongoliaLocations.find((item) => item.aimag === aimag);
  return [
    { value: '', label: aimag ? 'Сум/дүүрэг сонгох' : 'Эхлээд аймаг/хот сонгох' },
    ...(location?.soums.map((soum) => ({ value: soum, label: soum })) ?? []),
  ];
}

export function locationMatchesText(text: string, aimag: string, soum?: string) {
  if (!aimag && !soum) return true;

  const normalized = text.toLowerCase();
  const location = mongoliaLocations.find((item) => item.aimag === aimag);
  const matchesAimag = Boolean(aimag && normalized.includes(aimag.toLowerCase()));
  const matchesSelectedSoum = Boolean(soum && normalized.includes(soum.toLowerCase()));
  const matchesAnySoum = Boolean(!soum && location?.soums.some((item) => normalized.includes(item.toLowerCase())));

  return matchesAimag || matchesSelectedSoum || matchesAnySoum;
}
